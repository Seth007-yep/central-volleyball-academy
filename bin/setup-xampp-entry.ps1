param(
    [string] $HtdocsPath = 'C:\xampp\htdocs'
)

# Create a small public-only entry inside htdocs. The real PHP source,
# configuration, database, and session files stay in the VS Code workspace.
$projectRoot = (Resolve-Path -LiteralPath (Join-Path $PSScriptRoot '..')).Path
$publicIndex = (Resolve-Path -LiteralPath (Join-Path $projectRoot 'public\index.php')).Path
$publicAssets = (Resolve-Path -LiteralPath (Join-Path $projectRoot 'public\assets')).Path
$resolvedHtdocs = (Resolve-Path -LiteralPath $HtdocsPath).Path
$entryName = 'central_volleyball_academy'
$entryRoot = [System.IO.Path]::GetFullPath((Join-Path $resolvedHtdocs $entryName))
$rootPrefix = $resolvedHtdocs.TrimEnd('\') + '\'

# Refuse to create files outside the selected XAMPP htdocs directory.
if (-not $entryRoot.StartsWith($rootPrefix, [System.StringComparison]::OrdinalIgnoreCase)) {
    throw 'The resolved web entry is outside the XAMPP htdocs directory.'
}

$indexPath = Join-Path $entryRoot 'index.php'
$rulesPath = Join-Path $entryRoot '.htaccess'
$assetsPath = Join-Path $entryRoot 'assets'
$bridgeMarker = 'Central Volleyball Academy local XAMPP bridge generated by setup-xampp-entry.ps1.'

if (-not (Test-Path -LiteralPath $entryRoot)) {
    New-Item -ItemType Directory -Path $entryRoot -ErrorAction Stop | Out-Null
} elseif (Test-Path -LiteralPath $indexPath) {
    $existingIndex = Get-Content -LiteralPath $indexPath -Raw
    if (-not $existingIndex.Contains($bridgeMarker)) {
        throw 'The target htdocs folder already has an unrecognized index.php; it was left untouched.'
    }
} elseif ((Get-ChildItem -LiteralPath $entryRoot -Force | Measure-Object).Count -gt 0) {
    throw 'The target htdocs folder is not empty and has no recognized project bridge; it was left untouched.'
}

$publicIndexForPhp = $publicIndex.Replace('\', '/').Replace("'", "\\'")
$bridgeCode = @"
<?php

declare(strict_types=1);

// $bridgeMarker
// Keep all application source in the VS Code workspace and expose only public/.
putenv('APP_BASE_PATH=/central_volleyball_academy');
require '$publicIndexForPhp';
"@

$rewriteRules = @'
# Local-only front controller for the Central Volleyball Academy project.
Options -Indexes -MultiViews +FollowSymLinks
DirectoryIndex index.php
Require local

<IfModule mod_rewrite.c>
    RewriteEngine On
    RewriteCond %{REQUEST_FILENAME} !-f
    RewriteCond %{REQUEST_FILENAME} !-d
    RewriteRule ^ index.php [QSA,L]
</IfModule>

<FilesMatch "^\.">
    Require all denied
</FilesMatch>
'@

# Do not overwrite an unrelated file if a previous setup stopped partway.
if ((Test-Path -LiteralPath $indexPath) -and -not (Get-Content -LiteralPath $indexPath -Raw).Contains($bridgeMarker)) {
    throw 'The htdocs index changed during setup; refusing to overwrite it.'
}
if ((Test-Path -LiteralPath $rulesPath) -and -not (Get-Content -LiteralPath $rulesPath -Raw).Contains('Local-only front controller for the Central Volleyball Academy project.')) {
    throw 'The htdocs rewrite file already exists and is not managed by this script; it was left untouched.'
}
if (Test-Path -LiteralPath $assetsPath) {
    $assetEntry = Get-Item -LiteralPath $assetsPath -Force
    $resolvedAssetTarget = if ($assetEntry.LinkType -eq 'Junction') {
        (Resolve-Path -LiteralPath $assetEntry.Target).Path
    } else {
        ''
    }
    if ($assetEntry.LinkType -ne 'Junction' -or $resolvedAssetTarget -ne $publicAssets) {
        throw 'An unrelated assets path already exists in the htdocs entry; it was left untouched.'
    }
}

[System.IO.File]::WriteAllText($indexPath, $bridgeCode, [System.Text.UTF8Encoding]::new($false))
[System.IO.File]::WriteAllText($rulesPath, $rewriteRules, [System.Text.UTF8Encoding]::new($false))

if (Test-Path -LiteralPath $assetsPath) {
    # The preflight above confirmed this is the junction managed by this script.
} else {
    # A junction keeps CSS and other public assets synchronized with VS Code.
    New-Item -ItemType Junction -Path $assetsPath -Target $publicAssets -ErrorAction Stop | Out-Null
}

Write-Output 'The local Apache entry points to the workspace public directory. Open http://localhost/central_volleyball_academy/ to use it.'
